/** 获取 Elo 等级 */
export function getEloTier(elo: number): string {
  if (elo >= 2000) return 'S';
  if (elo >= 1800) return 'A';
  if (elo >= 1600) return 'B';
  if (elo >= 1400) return 'C';
  return 'D';
}

/** 获取 Elo 等级颜色 */
export function getEloTierColor(tier: string): string {
  switch (tier) {
    case 'S': return 'text-gold';
    case 'A': return 'text-green';
    case 'B': return 'text-blue-400';
    case 'C': return 'text-gray-400';
    default: return 'text-gray-500';
  }
}

/** 计算两队期望胜率 */
export function expectedScore(eloA: number, eloB: number): number {
  return 1.0 / (1.0 + Math.pow(10, (eloB - eloA) / 400.0));
}