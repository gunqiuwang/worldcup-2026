/** 获取状态描述 */
export function getFormDescription(form: TeamForm): string {
  const { form_score } = form;
  
  if (form_score >= 80) return '状态火热';
  if (form_score >= 60) return '状态良好';
  if (form_score >= 40) return '状态一般';
  return '状态低迷';
}

